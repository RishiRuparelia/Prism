import { readFileSync, writeFileSync, mkdirSync, cpSync } from 'node:fs';
import path from 'node:path';
import { prismNavigation } from './prism-navigation.mjs';
const root=process.cwd(),source=path.resolve('../prism-reference');
mkdirSync('public/prism',{recursive:true});
mkdirSync('outputs/previous-design',{recursive:true});
cpSync('app/page.tsx','outputs/previous-design/page.tsx');
cpSync('app/globals.css','outputs/previous-design/globals.css');
let html=readFileSync(path.join(source,'main/index.html'),'utf8');
html=html.replaceAll('src="uv/', 'src="/uv/');
html=html.replaceAll('/uv/uv.bundle.js', '/assets/runtime/engine.js').replaceAll('/uv/uv.config.js', '/assets/runtime/config.js');
html=html.replace(/<script\b[^>]*src=["'][^"']*(?:ezo|gatekeeper|dmca)[^"']*["'][^>]*><\/script>/gi,'');
html=html.replace(/<script>\s*window\.ezstandalone[\s\S]*?<\/script>/,'');
html=html.replace(/<!-- DMCA Badge -->[\s\S]*?(?=<\/body>)/,'');
const controller=html.match(/<script>\s*\/\/ ===== STARS =====[\s\S]*?<\/script>/)?.[0];
if(!controller)throw Error('Prism scene script not found');
html=html.replace(controller,'');
let script=controller.replace("'go.html'","'/prism/go.html'").replaceAll("'go.html'","'/prism/go.html'");
script=script.replaceAll("sessionStorage.setItem('prism_dest', abs);", "try { sessionStorage.setItem('prism_dest', abs); } catch { /* The destination is also passed in the frame URL. */ }")
  .replaceAll(".src = '/prism/go.html';", ".src = '/prism/go.html?url=' + encodeURIComponent(abs);");
script=script.replace("return 'https://duckduckgo.com/?q=' + encodeURIComponent(val);","let engine='duckduckgo'; try{engine=JSON.parse(localStorage.getItem('prism.settings')||'{}').engine||engine;}catch{} return (engine==='google'?'https://www.google.com/search?q=':'https://duckduckgo.com/?q=') + encodeURIComponent(val);");
html=html.replace('href="games.html"','href="/prism/games.html"').replace('href="apps.html"','href="/prism/movies.html"').replace('      APPS','      MOVIES').replace('href="settings.html"','href="/prism/settings.html"');
html=html.replace('<li><a href="/prism/settings.html">','<li><a href="/prism/chat.html">CHAT</a></li>\n    <li><a href="/prism/settings.html">');
html=html.replace('<a href="#">discord.gg/prism</a>','<a href="/credits.html">your corner of the internet</a>');
html=html.replace('onclick="doSearch(); return false;"','aria-label="Start browsing"');
html=html.replace('id="search-bar" type="text"','id="search-bar" aria-label="Search or enter address" type="text"');
html=html.replace('id="overlay-url" type="text"','id="overlay-url" aria-label="Browser address" type="text"');
html=html.replace('id="ov-back"','id="ov-back" aria-label="Back"').replace('id="ov-fwd"','id="ov-fwd" aria-label="Forward"').replace('id="ov-reload"','id="ov-reload" aria-label="Reload"');
html=html.replace('allow-orientation-lock allow-popups','allow-orientation-lock');
html=html.replace('<iframe id="proxy-iframe"','<iframe title="Proxy browser" id="proxy-iframe"');
html=html.replace('</head>','<link rel="icon" href="/favicon.svg"><link rel="stylesheet" href="/prism/enhancements.css"></head>');
html=html.replace('</body>',script+'\n<script src="/prism/preferences.js"></script>\n<a class="source-credit" href="/credits.html">SOURCE & CREDITS</a>\n</body>');
writeFileSync('public/prism/index.html',prismNavigation(html));
cpSync(path.join(source,'LICENSE'),'public/prism/LICENSE.txt');
// The root navigation shell in app/page.tsx is maintained separately.
writeFileSync('app/globals.css','*{box-sizing:border-box}body{margin:0;background:#0a0805;color:#e8dcc8;font-family:system-ui,sans-serif}\n');
console.log('Imported the original Prism homepage, scene, and license.');
